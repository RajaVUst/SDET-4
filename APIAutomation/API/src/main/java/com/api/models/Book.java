package com.api.models;

public class Book {

    private String isbn;
    private String title;
    private String subTitle;
    private String author;

    public String getIsbn() {
        return isbn;
    }

    public String getTitle() {
        return title;
    }

    public String getSubTitle() {
        return subTitle;
    }

    public String getAuthor() {
        return author;
    }
}